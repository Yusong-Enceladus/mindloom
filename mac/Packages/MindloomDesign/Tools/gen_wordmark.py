#!/usr/bin/env python3
"""Converts the drawn wordmark C (v10/brand/wordmark/mindloom-wordmark.json, the same paths as v10/system/kit.js
WORDMARK) into Swift source: Sources/MindloomDesign/Brand/WordmarkPaths.swift.

Each master is split into letters the way kit.js ML.wordmarkLetters does (subpaths whose x ranges overlap are one
letter: the i's dot and stem).  A letter is a flat [Double] of ops: 0 x y = move, 1 x y = line, 2 x1 y1 x2 y2 x y =
curve, 3 = close.  Units: cap height 100, y down, origin at the ink's left edge on the baseline.

usage: gen_wordmark.py <mindloom-wordmark.json> <out.swift>, then `xcrun swift-format format --in-place <out.swift>`
"""
import json, re, sys

def parse(d):
    toks = re.findall(r'[MLCZ]|-?\d+(?:\.\d+)?', d)
    ops, i, cmd = [], 0, None
    while i < len(toks):
        t = toks[i]
        if t in 'MLCZ':
            cmd = t; i += 1
            if t == 'Z': ops.append((3,)); continue
        n = {'M': 2, 'L': 2, 'C': 6}[cmd]
        vals = [float(v) for v in toks[i:i + n]]; i += n
        ops.append(({'M': 0, 'L': 1, 'C': 2}[cmd], *vals))
        if cmd == 'M': cmd = 'L'
    return ops

def subpaths(ops):
    out = []
    for op in ops:
        if op[0] == 0: out.append([])
        out[-1].append(op)
    return out

def xs(sp):
    v = []
    for op in sp:
        if op[0] in (0, 1): v.append(op[1])
        elif op[0] == 2: v += [op[1], op[3], op[5]]
    return v

def letters(d):
    boxes = sorted(({'ops': sp, 'x0': min(xs(sp)), 'x1': max(xs(sp))} for sp in subpaths(parse(d))), key=lambda b: b['x0'])
    out = []
    for b in boxes:
        if out and b['x0'] < out[-1]['x1'] - 0.5:
            out[-1]['ops'] += b['ops']; out[-1]['x1'] = max(out[-1]['x1'], b['x1'])
        else:
            out.append(dict(b))
    return out

def fmt(v):
    s = ('%.4f' % v).rstrip('0').rstrip('.')
    return s if s not in ('-0', '') else '0'

def main(src, dst):
    j = json.load(open(src))
    lines = ['// Generated by Tools/gen_wordmark.py from v10/brand/wordmark/mindloom-wordmark.json. Do not edit.',
             '// Wordmark C (drawn for Mindloom): cap height 100, y down, origin at the ink\'s left edge on the baseline.',
             '// Op codes: 0 x y = move, 1 x y = line, 2 x1 y1 x2 y2 x y = curve, 3 = close.', '',
             'enum WordmarkPaths {']
    for m in ('display', 'text'):
        v = j[m]
        lines.append(f'  static let {m} = WordmarkMasterData(')
        lines.append(f'    width: {fmt(v["width"])}, xHeight: {fmt(v["xHeight"])}, stem: {fmt(v["stem"])}, descender: {fmt(v["descender"])},')
        lines.append('    letters: [')
        for L in letters(v['d']):
            flat = []
            for op in L['ops']: flat += [fmt(x) for x in op]
            lines.append(f'      WordmarkLetterData(x0: {fmt(L["x0"])}, x1: {fmt(L["x1"])}, ops: [')
            for k in range(0, len(flat), 14):
                lines.append('        ' + ', '.join(flat[k:k + 14]) + ',')
            lines.append('      ]),')
        lines.append('    ])')
    lines.append('}')
    open(dst, 'w').write('\n'.join(lines) + '\n')

if __name__ == '__main__':
    main(sys.argv[1], sys.argv[2])
