// MARK: - Synthetic fixtures

func syntheticPNG(width: Int, height: Int, alpha: Bool = false) throws -> Data {
  let context = try XCTUnwrap(
    CGContext(
      data: nil, width: width, height: height, bitsPerComponent: 8, bytesPerRow: 0,
      space: CGColorSpace(name: CGColorSpace.sRGB)!,
      bitmapInfo: alpha
        ? CGImageAlphaInfo.premultipliedLast.rawValue : CGImageAlphaInfo.noneSkipLast.rawValue))
  // Noise-free gradient so JPEG sizes stay deterministic.
  for x in stride(from: 0, to: width, by: max(1, width / 16)) {
    context.setFillColor(
      red: CGFloat(x) / CGFloat(width), green: 0.4, blue: 0.6, alpha: alpha ? 0.5 : 1)
    context.fill(CGRect(x: x, y: 0, width: max(1, width / 16), height: height))
  }
  let image = try XCTUnwrap(context.makeImage())
  let output = NSMutableData()
  let destination = try XCTUnwrap(
    CGImageDestinationCreateWithData(output, UTType.png.identifier as CFString, 1, nil))
  CGImageDestinationAddImage(destination, image, nil)
  XCTAssertTrue(CGImageDestinationFinalize(destination))
  return output as Data
}

func syntheticTextPNG(_ text: String) throws -> Data {
  let width = 900
  let height = 200
  let context = try XCTUnwrap(
    CGContext(
      data: nil, width: width, height: height, bitsPerComponent: 8, bytesPerRow: 0,
      space: CGColorSpace(name: CGColorSpace.sRGB)!,
      bitmapInfo: CGImageAlphaInfo.noneSkipLast.rawValue))
  context.setFillColor(red: 1, green: 1, blue: 1, alpha: 1)
  context.fill(CGRect(x: 0, y: 0, width: width, height: height))
  let font = CTFontCreateWithName("Helvetica-Bold" as CFString, 64, nil)
  let line = CTLineCreateWithAttributedString(
    NSAttributedString(
      string: text,
      attributes: [.font: font, .foregroundColor: CGColor(gray: 0, alpha: 1)]))
  context.textPosition = CGPoint(x: 30, y: 70)
  CTLineDraw(line, context)
  let image = try XCTUnwrap(context.makeImage())
  let output = NSMutableData()
  let destination = try XCTUnwrap(
    CGImageDestinationCreateWithData(output, UTType.png.identifier as CFString, 1, nil))
  CGImageDestinationAddImage(destination, image, nil)
  XCTAssertTrue(CGImageDestinationFinalize(destination))
  return output as Data
}

func syntheticPDF(text: String?) throws -> Data {
  let output = NSMutableData()
  var box = CGRect(x: 0, y: 0, width: 300, height: 200)
  let consumer = try XCTUnwrap(CGDataConsumer(data: output))
  let context = try XCTUnwrap(CGContext(consumer: consumer, mediaBox: &box, nil))
  context.beginPDFPage(nil)
  if let text {
    let font = CTFontCreateWithName("Helvetica" as CFString, 14, nil)
    let line = CTLineCreateWithAttributedString(
      NSAttributedString(string: text, attributes: [.font: font]))
    context.textPosition = CGPoint(x: 20, y: 100)
    CTLineDraw(line, context)
  } else {
    context.setFillColor(gray: 0.3, alpha: 1)
    context.fill(CGRect(x: 20, y: 20, width: 200, height: 100))
  }
  context.endPDFPage()
  context.closePDF()
  return output as Data
}
