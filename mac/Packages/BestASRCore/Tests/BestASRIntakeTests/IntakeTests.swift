final class SourceApplicationTrackerTests: XCTestCase {
  private func app(_ bundle: String?, _ name: String?) -> TrackedApplication {
    TrackedApplication(bundleID: bundle, name: name, activatedAt: Date(timeIntervalSince1970: 1))
  }

  func testPasteUsesTheAppBeforeBestASR() {
    var state = SourceApplicationTrackerState(ownBundleID: "com.bestasr.app")
