  func testAssetStoreStagesCommitsDiscardsAndSweeps() throws {
    let store = IntakeAssetStore(assetRoot: root.appendingPathComponent("assets"))
    let external = root.appendingPathComponent("用户的文件.pdf")
    let bytes = try syntheticPDF(text: "Synthetic")
    try bytes.write(to: external)
    let id = SessionID()
    let attachments = try store.stage(
      sessionID: id,
      requests: [
        .init(
          role: .original, source: .file(external), originalFilename: "用户的文件.pdf",
          mediaType: "application/pdf", fileExtension: "pdf")
      ]
    )
    XCTAssertEqual(attachments.count, 1)
    let attachment = try XCTUnwrap(attachments.first)
    XCTAssertEqual(
      attachment.relativePath, "sessions/\(id.rawValue.uuidString.lowercased())/source/original.pdf"
    )
    XCTAssertEqual(
      attachment.digest.value, SHA256.hash(data: bytes).map { String(format: "%02x", $0) }.joined()
    )
    XCTAssertEqual(store.markedSessionIDs(), [id])
    XCTAssertThrowsError(
      try store.stage(
        sessionID: id,
        requests: [
          .init(
            role: .original, source: .data(Data([1])), originalFilename: "x", mediaType: "x",
            fileExtension: "x")
        ]), "a directory is never reused")

    store.commit(sessionID: id)
    XCTAssertEqual(store.markedSessionIDs(), [])
    store.discard(sessionID: id)
    XCTAssertTrue(
      FileManager.default.fileExists(
        atPath: root.appendingPathComponent("assets").appendingPathComponent(
          attachment.relativePath
        ).path),
      "a committed item's files are never discarded"
    )

    // Crash between staging and commit: the sweep removes only the unmarked-row case.
    let orphan = SessionID()
    let committedLate = SessionID()
    for staged in [orphan, committedLate] {
      _ = try store.stage(
        sessionID: staged,
        requests: [
          .init(
            role: .original, source: .data(Data("x".utf8)), originalFilename: "a.txt",
            mediaType: "text/plain", fileExtension: "txt")
        ])
    }
    let removed = store.sweep(existing: [committedLate], marked: store.markedSessionIDs())
    XCTAssertEqual(removed, 1)
    XCTAssertFalse(FileManager.default.fileExists(atPath: store.sessionDirectory(orphan).path))
    XCTAssertTrue(
      FileManager.default.fileExists(atPath: store.sessionDirectory(committedLate).path))
    XCTAssertEqual(store.markedSessionIDs(), [])
    XCTAssertTrue(FileManager.default.fileExists(atPath: external.path), "the user's file stays")
  }

