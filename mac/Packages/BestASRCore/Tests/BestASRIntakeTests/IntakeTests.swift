        .file(broken), id: brokenID, capturedAt: at, source: nil, origin: .finder)
    else { return XCTFail("broken image must be refused") }
    XCTAssertFalse(
      FileManager.default.fileExists(atPath: processor.assetStore.sessionDirectory(brokenID).path))

    let json = root.appendingPathComponent("codex-output.json")
    try Data(#"{"虚构": "结果"}"#.utf8).write(to: json)
    guard
      case .item(let data) = processor.prepare(
        .file(json), capturedAt: at, source: nil, origin: .finder)
    else { return XCTFail("json") }
    XCTAssertEqual(data.kind, .document)
    XCTAssertEqual(data.extractor, "plain-text-v1")
    XCTAssertEqual(data.attachments.map(\.mediaType), ["application/json"])
  }

