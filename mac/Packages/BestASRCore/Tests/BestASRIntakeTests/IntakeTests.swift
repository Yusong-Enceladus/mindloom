  func testImageNormalizerDownscalesAndChoosesFormat() throws {
    let opaque = try syntheticPNG(width: 4_000, height: 3_000, alpha: false)
    let normalized = try ImageNormalizer().normalize(opaque)
    XCTAssertEqual(normalized.mediaType, "image/jpeg")
