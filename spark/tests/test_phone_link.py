def wire_of(n_bytes: int, fill: bytes = b"\x5a") -> str:
    """A sealed-shaped wire string of n sealed bytes (not a real seal: the Spark never opens one)."""
    return sealed.PREFIX + base64.urlsafe_b64encode(fill * n_bytes).decode().rstrip("=")


def sealed_body(entry_id: str = V_ID, wire: str = V_WIRE, **over) -> dict:
    body = {"inbox_id": entry_id, "source": "sealed", "kind": "sealed", "blob": wire, "received_at": WHEN}
    body.update(over)
    return body


def phone_reply(stdout: str) -> dict:
    """What the phone app reads: the last line of stdout that is a JSON object (InboxGateReply)."""
    for line in reversed(stdout.splitlines()):
        try:
            obj = json.loads(line.strip())
        except ValueError:
            continue
        if isinstance(obj, dict):
            return obj
    raise AssertionError(f"no JSON line in {stdout!r}")


def files_under(root: Path) -> list[Path]:
    return [p for p in root.rglob("*") if p.is_file()]


