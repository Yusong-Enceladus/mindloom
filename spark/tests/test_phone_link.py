def test_a_page_reads_only_the_entries_it_returns(tmp_path):
    store = InboxStore(tmp_path / "inbox.db")
    ids = [f"22222222-3333-4444-8555-66666666666{i}" for i in range(4)]
    for i, n in zip(ids, (300, 300, 5000, 10)):
        store.add(sealed_body(i, wire_of(n)), None)
    statements: list[str] = []
    store.conn.set_trace_callback(statements.append)
    rows, more = store.page(0, 20, budget=1000)          # 408 + 408 chars fit, the 6,675-char one does not
    assert [r["inbox_id"] for r in rows] == ids[:2] and more is True
    content_reads = [q for q in statements if "SELECT inbox_id" in q]
    assert len(content_reads) == 1 and "seq <=" in content_reads[0]  # only the chosen range is read
    rows, more = store.page(rows[-1]["seq"], 20, budget=1000)
    assert [r["inbox_id"] for r in rows] == [ids[2]] and more is True  # alone, over the budget
    rows, more = store.page(rows[-1]["seq"], 20, budget=1000)
    assert [r["inbox_id"] for r in rows] == [ids[3]] and more is False
    assert store.page(rows[-1]["seq"], 20, budget=1000) == ([], False)
    assert store.page(0, 2, budget=10 ** 9)[1] is True     # a full page may have more behind it
    store.close()


