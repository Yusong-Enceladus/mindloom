def shells() -> list[str]:
    found = []
    for name in ("sh", "dash", "bash"):
        path = shutil.which(name)
        if path and os.path.realpath(path) not in {os.path.realpath(f) for f in found}:
            found.append(path)
    return found


def relay(home: Path, *args: str, shell: str = "sh") -> tuple[int, dict, str]:
    """Run the helper exactly as the Mac does: the script on stdin (`sh -s -- …`), arguments as plain words."""
    r = subprocess.run([shell, "-s", "--", *args], input=RELAY_HELPER.read_bytes(), capture_output=True,
                       env={"PATH": os.environ.get("PATH", "/usr/bin:/bin"), "HOME": str(home)}, timeout=30)
    return r.returncode, json.loads(r.stdout.decode().strip().splitlines()[-1]), r.stderr.decode()


