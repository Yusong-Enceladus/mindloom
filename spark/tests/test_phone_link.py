def ssh(rig, port: int, *args: str, stdin: bytes = b"", timeout: float = 60, extra: tuple = ()):
    """The phone's side, played by OpenSSH: only the phone key, only pinned host keys, no user config."""
    base = ["ssh", "-F", "/dev/null", "-o", "BatchMode=yes", "-o", "IdentitiesOnly=yes", "-o", "IdentityAgent=none",
            "-o", f"UserKnownHostsFile={rig['root'] / 'known_hosts'}", "-o", "GlobalKnownHostsFile=/dev/null",
            "-o", "StrictHostKeyChecking=yes", "-o", "LogLevel=ERROR", "-i", str(rig["root"] / "phone"),
            "-p", str(port), *extra, f"{getpass.getuser()}@127.0.0.1", *args]
    try:
        return subprocess.run(base, input=stdin, capture_output=True, timeout=timeout)
    except subprocess.TimeoutExpired as exc:
        return subprocess.CompletedProcess(base, "timeout", exc.stdout or b"", exc.stderr or b"")


def test_sshd_holds_the_phone_key_to_the_gate(ssh_rig):
    rig = ssh_rig
    out = phone_keys.authorize("sim1", rig["phone_pub"], path=rig["spark_ak"], gate_path=str(rig["gate"]))
    assert out["changed"] is True
    port = rig["spark"].port
    # the largest sealed entry, through sshd's forced command, on stdin
    biggest = wire_of(sealed.MAX_SEALED_BYTES, b"\x33")
    r = ssh(rig, port, f"zhiji-inbox add --sealed --id {V_ID} --json", stdin=biggest.encode(), timeout=120)
    assert r.returncode == 0, r.stderr
    assert phone_reply(r.stdout.decode()) == {"ok": True, "id": V_ID, "inbox_id": V_ID, "duplicate": False}
    assert rig["org"].inbox.one(V_ID)["blob"] == biggest
    r = ssh(rig, port, f"zhiji-inbox add --sealed --id {V_ID} --json", stdin=biggest.encode(), timeout=120)
    assert phone_reply(r.stdout.decode())["duplicate"] is True
    r = ssh(rig, port, "zhiji-inbox status")
    assert r.returncode == 0 and "1 条" in r.stdout.decode()
    # anything else is refused by the gate: other commands, the admin commands, a shell
    for cmd in ("cat /etc/hosts", f"zhiji-inbox authorize-phone --key-id x --pubkey '{rig['phone_pub']}' --json",
                "zhiji-inbox list-phones --json", "zhiji-inbox revoke-phone --key-id sim1 --json", "sh -i", ""):
        r = ssh(rig, port, *([cmd] if cmd else []))
        assert r.returncode == 1, (cmd, r.stdout, r.stderr)
    assert not (rig["home"] / ".ssh" / "authorized_keys").exists()
    assert phone_keys.list_phones(path=rig["spark_ak"])["phones"][0]["key_id"] == "sim1"
    # restrict: no port forwarding from the Spark
    r = ssh(rig, port, timeout=10, extra=("-W", f"127.0.0.1:{port}"))
    assert r.returncode != 0
    # revoked: the key no longer gets in at all
    phone_keys.revoke("sim1", path=rig["spark_ak"])
    r = ssh(rig, port, "zhiji-inbox status")
    assert r.returncode == 255 and b"denied" in r.stderr.lower()


def test_sshd_holds_the_phone_key_on_the_relay_to_one_tunnel(ssh_rig):
    rig = ssh_rig
    spark_port, relay_port = rig["spark"].port, rig["relay"].port
    phone_keys.authorize("sim1", rig["phone_pub"], path=rig["spark_ak"], gate_path=str(rig["gate"]))
    ktype, b64 = rig["phone_pub"].split()[:2]
    rc, out, err = relay(rig["relay_home"], "add", "sim1", "127.0.0.1", str(spark_port), ktype, b64)
    assert rc == 0 and out["changed"] is True, err
    # phone -> relay (tunnel) -> Spark gate, the way the phone app connects
    jump = ("-o", "ProxyCommand=" + " ".join([
        "ssh", "-F", "/dev/null", "-o", "BatchMode=yes", "-o", "IdentitiesOnly=yes", "-o", "IdentityAgent=none",
        "-o", f"UserKnownHostsFile={rig['root'] / 'known_hosts'}", "-o", "StrictHostKeyChecking=yes",
        "-o", "LogLevel=ERROR", "-i", str(rig["root"] / "phone"), "-p", str(relay_port), "-W", "%h:%p",
        f"{getpass.getuser()}@127.0.0.1"]))
    r = ssh(rig, spark_port, f"zhiji-inbox add --sealed --id {V_ID} --json", stdin=V_WIRE.encode(), extra=jump)
    assert r.returncode == 0, r.stderr
    assert phone_reply(r.stdout.decode())["ok"] is True
    # on the relay the key can do nothing else: no command, no other tunnel target, no listening port
    r = ssh(rig, relay_port, "echo RAN-ON-RELAY")
    assert b"RAN-ON-RELAY" not in r.stdout and r.returncode != 0
    r = ssh(rig, relay_port, timeout=10, extra=("-W", f"127.0.0.1:{relay_port}"))
    assert r.returncode != 0
    r = ssh(rig, relay_port, timeout=5, extra=("-N", "-o", "ExitOnForwardFailure=yes", "-R", "127.0.0.1:0:127.0.0.1:9"))
    assert r.returncode not in (0, "timeout"), r.stderr
    # unpairing on the relay closes the tunnel
    rc, out, _ = relay(rig["relay_home"], "remove", "sim1")
    assert rc == 0 and out["removed"] == 1
    r = ssh(rig, spark_port, "zhiji-inbox status", extra=jump)
    assert r.returncode != 0
