def test_sealed_entries_refuse_anything_but_the_contract_shape(client):
    bad = [
        sealed_body(entry_id=V_ID.upper()),                 # the id is in the AAD: never normalized, refused
        sealed_body(entry_id=None),                         # a sealed entry cannot be opened without its id
        sealed_body(entry_id="5b0d7c1e2f4a4c619d3e8a7b6c5d4e3f0000"),
        sealed_body(wire="mlseal2." + V_WIRE[8:]),
        sealed_body(wire=V_WIRE + "="),
        sealed_body(wire=wire_of(sealed.MIN_SEALED_BYTES - 1)),
        sealed_body(wire=None),
        sealed_body(source="iPhone"),                       # no plaintext metadata next to a sealed blob
        sealed_body(text="明文"),
        sealed_body(image_b64=TINY_PNG_B64),
        {"source": "iPhone", "kind": "text", "text": "x", "blob": V_WIRE, "received_at": WHEN},
    ]
    for body in bad:
        r = client.post("/v1/inbox", json=body)
        assert r.status_code == 422, body
        # the refusal does not echo the entry back (no plaintext share, no 48 MB blob in an error)
        assert V_WIRE[8:40] not in r.text and "明文" not in r.text and len(r.text) < 1000
    assert client.get("/v1/inbox").json()["items"] == []
    # other routes keep FastAPI's usual validation answer
    other = client.get("/v1/debug/runs", params={"limit": 0})
    assert other.status_code == 422 and "input" in other.json()["detail"][0]


