def test_plaintext_adds_are_refused_and_nothing_is_sent(client, capsys):
    """The iOS Shortcut path is retired: it cannot seal, so its shares would wait here in plaintext (review F9).
    A plaintext add is refused before the organizer is contacted; the API refuses one too, without echoing it."""
    sent = []
    client.app.state.organizer.inbox.add = lambda *a, **k: sent.append(a)  # would be called on a store
    for argv, stdin in ((["add", "--json"], "快捷指令分享的一段".encode()),
                        (["add", "--source", "iPhone", "--json"], b"x"),
                        (["add", "--id", "1b4e28ba-2fa1-11d2-883f-0016d3cca427", "--json"], b"x"),
                        (["add", "--image", "-", "--json"], base64.b64encode(base64.b64decode(TINY_PNG_B64))),
                        (["add", "--text", "hi", "--json"], b"")):
        assert inbox_cli.main(argv, stdin=stdin, client=client) == 1
        assert phone_reply(capsys.readouterr().out) == {"ok": False, "error": "not_sealed"}
    for body in ({"source": "iPhone", "kind": "text", "text": "快捷指令分享的一段", "received_at": WHEN},
                 {"source": "iPhone", "kind": "image", "image_b64": TINY_PNG_B64, "received_at": WHEN},
                 {"inbox_id": V_ID, "source": "sealed", "kind": "text", "text": "x", "received_at": WHEN}):
        r = client.post("/v1/inbox", json=body)
        assert r.status_code == 422 and "快捷指令" not in r.text and TINY_PNG_B64 not in r.text
    assert sent == []


