def test_wire_shape_limits_follow_the_phone():
    # 36,000,000 sealed bytes before base64url, the phone's MindloomSeal.maximumWireBytes
    assert sealed.MAX_WIRE_CHARS == 48_000_008
    assert sealed.wire_problem(V_WIRE) is None
    assert sealed.wire_problem(wire_of(sealed.MIN_SEALED_BYTES)) is None
    assert len(wire_of(sealed.MIN_SEALED_BYTES)) == sealed.MIN_WIRE_CHARS == 88
    assert sealed.wire_problem(wire_of(sealed.MIN_SEALED_BYTES - 1)) == "too_short"
    biggest = wire_of(sealed.MAX_SEALED_BYTES)
    assert len(biggest) == sealed.MAX_WIRE_CHARS and sealed.wire_problem(biggest) is None
    assert sealed.wire_problem(biggest + "A") == "too_large"
    assert sealed.wire_problem("mlseal2." + V_WIRE[8:]) == "not_sealed"
    assert sealed.wire_problem(V_WIRE[8:]) == "not_sealed"
    assert sealed.wire_problem(V_WIRE + "=") == "malformed"          # padding is not base64url_nopad
    assert sealed.wire_problem(V_WIRE[:-3] + "+/Q") == "malformed"   # the standard alphabet is not base64url
    assert sealed.wire_problem(V_WIRE[:-2] + "é") == "malformed"
    whole_groups = sealed.PREFIX + "A" * 400
    assert sealed.wire_problem(whole_groups) is None
    assert sealed.wire_problem(whole_groups + "A") == "malformed"  # unpadded base64 never ends in 1 character
    assert sealed.wire_problem(whole_groups + "AA") is None and sealed.wire_problem(whole_groups + "AAA") is None
    assert sealed.is_entry_id(V_ID) and not sealed.is_entry_id(V_ID.upper()) and not sealed.is_entry_id(V_ID[:-1])


