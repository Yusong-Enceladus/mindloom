def ed25519_blob(raw32: bytes) -> bytes:
    name = b"ssh-ed25519"
    return len(name).to_bytes(4, "big") + name + (32).to_bytes(4, "big") + raw32


def pubkey(seed: int, comment: str = "") -> str:
    b64 = base64.b64encode(ed25519_blob(bytes([seed]) * 32)).decode()
    return f"ssh-ed25519 {b64}" + (f" {comment}" if comment else "")


