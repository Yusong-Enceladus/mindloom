def test_what_the_mac_gets_back_opens_with_the_id_it_was_sealed_under(client):
    """The Mac side of section 5, done here with the vector's Mac key: the stored blob and id are the phone's."""
    x25519 = pytest.importorskip("cryptography.hazmat.primitives.asymmetric.x25519")
    from cryptography.hazmat.primitives import hashes
    from cryptography.hazmat.primitives.ciphers.aead import ChaCha20Poly1305
    from cryptography.hazmat.primitives.kdf.hkdf import HKDF

    client.post("/v1/inbox", json=sealed_body())
    entry = client.get("/v1/inbox").json()["items"][0]
    raw = base64.urlsafe_b64decode(entry["blob"][len(sealed.PREFIX):] + "=" * (-len(entry["blob"][8:]) % 4))
    mac = x25519.X25519PrivateKey.from_private_bytes(bytes.fromhex(V_MAC_PRIV))
    eph, nonce, box = raw[:32], raw[32:44], raw[44:]
    mac_pub = mac.public_key().public_bytes_raw()
    shared = mac.exchange(x25519.X25519PublicKey.from_public_bytes(eph))
    key = HKDF(hashes.SHA256(), 32, salt=eph + mac_pub, info=b"mindloom-inbox-seal-v1").derive(shared)
    plain = ChaCha20Poly1305(key).decrypt(nonce, box, ("mindloom-inbox-v1|" + entry["inbox_id"]).encode())
    payload = json.loads(plain)
    assert payload["kind"] == "text" and payload["source"] == "iPhone 键盘" and V_PLAINTEXT_PHRASE in payload["text"]
    with pytest.raises(Exception):  # an id changed in any way (for example upper-cased) no longer opens
        ChaCha20Poly1305(key).decrypt(nonce, box, ("mindloom-inbox-v1|" + entry["inbox_id"].upper()).encode())


