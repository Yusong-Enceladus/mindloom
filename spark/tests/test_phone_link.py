def test_cli_sealed_refusals_answer_in_json_and_send_nothing(client, capsys):
    cases = [
        (["add", "--sealed", "--json"], V_WIRE, "bad_id"),
        (["add", "--sealed", "--id", V_ID.upper(), "--json"], V_WIRE, "bad_id"),
        (["add", "--sealed", "--id", V_ID, "--source", "iPhone", "--json"], V_WIRE, "bad_args"),
        (["add", "--sealed", "--id", V_ID, "--image", "-", "--json"], V_WIRE, "bad_args"),
        (["add", "--sealed", "--id", V_ID, "--json"], "明文不是封好的", "malformed"),
        (["add", "--sealed", "--id", V_ID, "--json"], "hello", "not_sealed"),
        (["add", "--sealed", "--id", V_ID, "--json"], V_WIRE + "=", "malformed"),
        (["add", "--sealed", "--id", V_ID, "--json"], "", "not_sealed"),
    ]
