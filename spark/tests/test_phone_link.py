# ---- the real thing: OpenSSH's sshd enforcing both lines ----------------------------------------------------


def free_port() -> int:
    with socket.socket() as s:
        s.bind(("127.0.0.1", 0))
        return s.getsockname()[1]


class SSHD:
    """A throwaway sshd on 127.0.0.1 run as this user, reading keys only from `authorized_keys`."""

    def __init__(self, root: Path, name: str, authorized_keys: Path):
        self.port = free_port()
        self.root = root
        hostkey = root / f"{name}_hostkey"
        subprocess.run(["ssh-keygen", "-q", "-t", "ed25519", "-N", "", "-f", str(hostkey)], check=True)
        self.host_key = (root / f"{name}_hostkey.pub").read_text().split()[:2]
        config = root / f"{name}_sshd_config"
        config.write_text("\n".join([
            f"Port {self.port}", "ListenAddress 127.0.0.1", f"HostKey {hostkey}",
            f"AuthorizedKeysFile {authorized_keys}", f"PidFile {root / (name + '.pid')}", "UsePAM no",
            "StrictModes no", "PasswordAuthentication no", "KbdInteractiveAuthentication no",
            "PermitUserEnvironment no", "AllowTcpForwarding yes", "LogLevel VERBOSE", ""]))
        self.log = root / f"{name}.log"
        self.proc = subprocess.Popen([sshd_binary(), "-D", "-f", str(config),
                                      "-E", str(self.log)], stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
        for _ in range(100):
            with socket.socket() as s:
                if s.connect_ex(("127.0.0.1", self.port)) == 0:
                    return
            if self.proc.poll() is not None:
                break
            time.sleep(0.05)
        self.stop()
        pytest.skip("sshd would not start as this user: " + (self.log.read_text()[-300:] if self.log.exists() else ""))

    def known_hosts_line(self) -> str:
        return f"[127.0.0.1]:{self.port} {' '.join(self.host_key)}\n"

    def stop(self) -> None:
        if self.proc.poll() is None:
            self.proc.terminate()
            try:
                self.proc.wait(timeout=5)
            except subprocess.TimeoutExpired:
                self.proc.kill()


def sshd_binary() -> str | None:
    return shutil.which("sshd") or next((p for p in ("/usr/sbin/sshd", "/usr/bin/sshd") if os.path.exists(p)), None)


